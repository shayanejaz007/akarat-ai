// Mirrors data/locations.js into lib/shared/reference/places_data.g.dart,
// and writes test/fixtures/places_parity.json: what the website's search
// (lib/places.js) answers for a set of queries, which the app's search
// (lib/shared/reference/places.dart) must answer the same way.
//
// data/locations.js is built from GeoNames (scripts/build-locations.mjs) and
// seeds the database (supabase/migrations/0023_locations.sql). After
// rebuilding it, run from mobile/:
//
//   node tool/gen_places.mjs

import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const LOC = await import(pathToFileURL(join(root, 'data', 'locations.js')).href);
const { createPlaces } = await import(pathToFileURL(join(root, 'lib', 'places.js')).href);

const s = v => `'${String(v ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const list = xs => `[${(xs || []).map(s).join(', ')}]`;
const num = n => (n == null ? '0.0' : Number.isInteger(n) ? n.toFixed(1) : String(n));

const lines = [
  '// GENERATED by tool/gen_places.mjs from data/locations.js. Do not edit.',
  '// Place names beyond the hand-checked core are from GeoNames (geonames.org), CC BY 4.0.',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  "part of 'places.dart';",
  '',
  `const List<Place> _governorates = [`,
  ...LOC.GOVERNORATES.map(g => `  Place(PlaceKind.gov, ${s(g.id)}, null, ${s(g.en)}, ${s(g.ar)}, ${num(g.lat)}, ${num(g.lng)}, ${list(g.alt)}, true),`),
  '];',
  '',
  `const List<Place> _cities = [`,
  ...LOC.CITIES.map(c => `  Place(PlaceKind.city, ${s(c.id)}, ${s(c.gov)}, ${s(c.en)}, ${s(c.ar)}, ${num(c.lat)}, ${num(c.lng)}, ${list(c.alt)}, ${c.core ? 'true' : 'false'}),`),
  '];',
  '',
  `const List<Place> _neighborhoods = [`,
  ...LOC.NEIGHBORHOODS.map(n => `  Place(PlaceKind.hood, ${s(n.id)}, ${s(n.city)}, ${s(n.en)}, ${s(n.ar)}, ${num(n.lat)}, ${num(n.lng)}, ${list(n.alt)}, ${n.core ? 'true' : 'false'}),`),
  '];',
  '',
];
const dataFile = join(here, '..', 'lib', 'shared', 'reference', 'places_data.g.dart');
writeFileSync(dataFile, lines.join('\n'));
// The quality gate runs `dart format --set-exit-if-changed`: leave it formatted.
try {
  // Through the shell (dart is a .bat on Windows), with our own path quoted.
  execSync(`dart format "${dataFile}"`, { stdio: 'ignore' });
} catch {
  console.warn('dart format did not run: run it on places_data.g.dart before committing');
}

// What the website answers. Both languages, misspellings, every level.
const places = createPlaces(LOC);
const QUERIES = [
  'abdoun', 'abdoon', 'عبدون', 'swaifieh', 'sweifieh', 'الصويفية', 'shmeisani', 'jabal amman', 'um uthaina', 'dabouq',
  'irbid', 'اربد', 'إربد', 'الزرقا', 'zarka', 'petra', 'salt', 'السلط', 'kufranja', 'ajlun', 'aqaba', 'العقبة', 'ramtha',
  'الرمثا', 'madaba', 'مادبا', 'karak', 'الكرك', 'mafraq', 'tafilah', 'الطفيلة', "ma'an", 'معان', 'jerash', 'جرش',
  'irbid governorate', 'محافظة إربد', 'khalda', 'خلدا', 'tlaa al ali', 'تلاع العلي', 'marj al hamam', 'sahab', 'سحاب',
  'deir alla', 'fuheis', 'الفحيص', 'wadi musa', 'azraq', 'الأزرق', 'ghor al safi', 'zz', 'qq', '',
];
const fixtures = QUERIES.map(q => {
  const lang = /[؀-ۿ]/.test(q) ? 'ar' : 'en';
  return {
    q,
    lang,
    hits: places.search(q, { lang, limit: 5 }).map(h => ({
      kind: h.kind, id: h.id, label: h.label, gov: h.governorate_id, city: h.city_id, hood: h.neighborhood_id,
    })),
  };
});
const labels = [['amman', 'abdoun'], ['ramtha', null], ['irbid', null], [null, null], ['aqaba', null]]
  .flatMap(([c, h]) => ['en', 'ar'].map(lang => ({ city: c, hood: h, lang, label: places.placeLabel(c, h, lang) })));
mkdirSync(join(here, '..', 'test', 'fixtures'), { recursive: true });
writeFileSync(
  join(here, '..', 'test', 'fixtures', 'places_parity.json'),
  JSON.stringify({ counts: { governorates: places.governorates.length, cities: places.cities.length, hoods: places.hoods.length }, search: fixtures, labels }, null, 1) + '\n',
);
console.log(`places: ${LOC.GOVERNORATES.length} governorates, ${LOC.CITIES.length} cities, ${LOC.NEIGHBORHOODS.length} neighbourhoods; ${fixtures.length} parity queries`);
