// Mirrors data/market.js into lib/shared/reference/market_data.g.dart.
//
// The website does the same for its server pages (scripts/gen-reference.mjs
// writes lib/reference.ts). data/market.js stays the single source of truth for
// cities, areas, property types and amenities; both clients are generated from
// it, and the cities/neighborhoods tables in Postgres are seeded from it by
// migration 0009. Edit market.js, then run from mobile/:
//
//   node tool/gen_reference.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const market = await import(pathToFileURL(join(root, 'data', 'market.js')).href);

const s = v => (v == null ? 'null' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`);
const list = xs => `[${xs.map(s).join(', ')}]`;
const num = n => (Number.isInteger(n) ? n.toFixed(1) : String(n));

const lines = [];
lines.push('// GENERATED by tool/gen_reference.mjs from data/market.js. Do not edit.');
lines.push('// ignore_for_file: lines_longer_than_80_chars');
lines.push('');
lines.push("part of 'market_data.dart';");
lines.push('');
lines.push('const List<City> _cities = [');
for (const c of market.CITIES) {
  lines.push(`  City(id: ${s(c.id)}, en: ${s(c.en)}, ar: ${s(c.ar)}, lat: ${num(c.lat)}, lng: ${num(c.lng)}, alt: ${list(c.alt || [])}),`);
}
lines.push('];');
lines.push('');
lines.push('const List<Neighborhood> _neighborhoods = [');
for (const n of market.NEIGHBORHOODS) {
  lines.push(`  Neighborhood(id: ${s(n.id)}, city: ${s(n.city)}, en: ${s(n.en)}, ar: ${s(n.ar)}, lat: ${num(n.lat)}, lng: ${num(n.lng)}, alt: ${list(n.alt || [])}),`);
}
lines.push('];');
lines.push('');
lines.push('const List<Amenity> _amenities = [');
for (const a of market.AMENITIES) lines.push(`  Amenity(id: ${s(a.id)}, en: ${s(a.en)}, ar: ${s(a.ar)}),`);
lines.push('];');
lines.push('');
lines.push('const List<PropertyType> _types = [');
for (const t of market.TYPES) lines.push(`  PropertyType(id: ${s(t.id)}, en: ${s(t.en)}, ar: ${s(t.ar)}),`);
lines.push('];');
lines.push('');
lines.push('const Map<String, double> _sourceConfidence = {');
for (const [k, v] of Object.entries(market.SOURCE_CONFIDENCE)) lines.push(`  ${s(k)}: ${num(v)},`);
lines.push('};');
lines.push('');

const target = join(here, '..', 'lib', 'shared', 'reference', 'market_data.g.dart');
writeFileSync(target, lines.join('\n'), 'utf8');
console.log(`wrote ${target}`);
