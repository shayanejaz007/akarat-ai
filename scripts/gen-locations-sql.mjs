// Writes supabase/migrations/0009_locations.sql from data/market.js.
//
// properties.city_id and properties.neighborhood_id are foreign keys into the
// cities and neighborhoods tables. The listing form offers whatever is in
// data/market.js, so any place that exists there but not in the database makes
// the insert fail with "violates foreign key constraint
// properties_neighborhood_id_fkey". Generating the SQL from the same file the
// form reads is what keeps the two from drifting apart again.
//
// Run after adding or renaming a place:  node scripts/gen-locations-sql.mjs
// then run the regenerated file in the Supabase SQL editor.
import { writeFile } from 'node:fs/promises';

const m = await import('../data/market.js');
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${(xs || []).map(q).join(', ')}]::text[]`;

const cities = m.CITIES.map((c) =>
  `  (${q(c.id)}, ${q(c.en)}, ${q(c.ar)}, ${c.lat ?? 'null'}, ${c.lng ?? 'null'})`).join(',\n');

const hoods = m.NEIGHBORHOODS.map((n) =>
  `  (${q(n.id)}, ${q(n.city)}, ${q(n.en)}, ${q(n.ar)}, ${n.lat ?? 'null'}, ${n.lng ?? 'null'}, ${arr(n.alt)})`).join(',\n');

const sql = `-- 0009_locations.sql
-- GENERATED by scripts/gen-locations-sql.mjs from data/market.js. Do not edit
-- by hand; edit data/market.js and regenerate.
--
-- Brings the cities and neighborhoods tables in line with every place the
-- listing form offers (${m.CITIES.length} cities, ${m.NEIGHBORHOODS.length} neighbourhoods). Without it, choosing an
-- area that exists only in the app fails the insert with
-- "violates foreign key constraint properties_neighborhood_id_fkey".
--
-- Safe to run more than once: rows are upserted, never duplicated, and no
-- listing is touched.

insert into public.cities (id, name_en, name_ar, lat, lng) values
${cities}
on conflict (id) do update
  set name_en = excluded.name_en,
      name_ar = excluded.name_ar,
      lat     = excluded.lat,
      lng     = excluded.lng;

insert into public.neighborhoods (id, city_id, name_en, name_ar, lat, lng, aliases) values
${hoods}
on conflict (id) do update
  set city_id = excluded.city_id,
      name_en = excluded.name_en,
      name_ar = excluded.name_ar,
      lat     = excluded.lat,
      lng     = excluded.lng,
      aliases = excluded.aliases;

notify pgrst, 'reload schema';
`;

await writeFile(new URL('../supabase/migrations/0009_locations.sql', import.meta.url), sql);
console.log(`gen-locations-sql: 0009_locations.sql written (${m.CITIES.length} cities, ${m.NEIGHBORHOODS.length} neighbourhoods)`);
